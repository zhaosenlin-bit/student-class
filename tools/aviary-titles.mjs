/* ---------------------------------------------------------- the engine -- */

const phraseKeys = Object.keys(PHRASES).sort((a, b) => b.length - a.length);
const wordKeys = Object.keys(WORDS).sort((a, b) => b.length - a.length);
const nameKeys = Object.keys(NAMES).sort((a, b) => b.length - a.length);

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/* The shape of the name: the part that says "of" or "from" or "on". */
const SHAPES = [
  [/(.+?)\s+due\s+to\s+(.+)/i, (a, b) => `${b}引起的${a}`],
  [/(.+?)\s+from\s+(.+)/i, (a, b) => `由${b}求${a}`],
  [/(.+?)\s+of\s+(.+)/i, (a, b) => `${b}的${a}`],
  [/(.+?)\s+on\s+(.+)/i, (a, b) => `${b}上的${a}`],
  [/(.+?)\s+in\s+(.+)/i, (a, b) => `${b}中的${a}`],
  [/(.+?)\s+with\s+(.+)/i, (a, b) => `含${b}的${a}`],
  [/(.+?)\s+at\s+(.+)/i, (a, b) => `${b}处的${a}`],
  [/(.+?)\s+for\s+(.+)/i, (a, b) => `${b}的${a}`],
  [/(.+?)\s+between\s+(.+)/i, (a, b) => `${b}之间的${a}`],
  [/(.+?)\s+through\s+(.+)/i, (a, b) => `穿过${b}的${a}`],
  [/(.+?)\s+about\s+(.+)/i, (a, b) => `关于${b}的${a}`],
  [/(.+?)\s+by\s+(.+)/i, (a, b) => `${b}的${a}`],
];

const tidy = (s) =>
  s
    .replace(/\s{2,}/g, ' ')
    .replace(/([一-鿿])\s+([一-鿿])/g, '$1$2')
    .replace(/([一-鿿])\s+([一-鿿])/g, '$1$2')
    .replace(/([一-鿿])\s+([一-鿿])/g, '$1$2')
    .replace(/[，、。：；]+$/g, '')
    .replace(/^(的|在|含|由|与|和|个)\s*/, '')
    .replace(/的的/g, '的')
    .trim();

function lookup(text) {
  let out = text;

  /* The names of people first, so "Newton" is not read as a word. */
  for (const key of nameKeys) {
    const re = new RegExp(`(^|[^A-Za-z])${escapeRe(key)}([^A-Za-z]|$)`, 'gi');
    out = out.replace(re, (m, a, b) => `${a}${NAMES[key]}${b}`);
  }

  for (const key of phraseKeys) {
    const re = new RegExp(
      `(^|[^A-Za-z])${escapeRe(key)}([^A-Za-z]|$)`,
      'gi'
    );
    out = out.replace(re, (m, a, b) => `${a}${PHRASES[key.toLowerCase()]}${b}`);
  }

  return out;
}

function applyWords(text) {
  let out = text;

  for (const key of wordKeys) {
    const re = new RegExp(`(^|[^A-Za-z])${escapeRe(key)}([^A-Za-z]|$)`, 'gi');
    out = out.replace(re, (m, a, b) => `${a}${WORDS[key]}${b}`);
  }

  /* What is left of the English words that have no Chinese name here is
     kept, so nothing becomes a row of empty spaces. */
  out = out
    .split(/(\s+)/)
    .map((p) => {
      if (/^\s+$/.test(p)) return p;
      if (/[A-Za-z0-9]/.test(p) && !/[一-鿿]/.test(p)) {
        const lower = p.toLowerCase().replace(/[.,:;'"()]/g, '');
        if (NOISE.has(lower)) return '';
        if (SUFFIXES[lower] !== undefined) return SUFFIXES[lower];
        return p;
      }
      return p;
    })
    .join('');

  return out;
}

function translateOnce(text, depth) {
  let s = ` ${String(text || '').replace(/\s+/g, ' ').trim()} `;
  s = s.replace(/['’]s\s+/gi, ' ');
  s = s.replace(TITLE_PREFIX, '');

  /* The word that says what kind of program this is belongs at the end
     of the Chinese name, so it is taken off and put back later. */
  let kind = '';
  const tail = s.match(/^(.*\S)\s+(lab|problem|challenge|review)\s*$/i);
  if (tail) {
    kind = SUFFIXES[tail[2].toLowerCase()] || '';
    s = ` ${tail[1]} `;
  }

  /* The phrases that have to be read as a whole are found first: after
     that the shape of the name can be read without stumbling over a
     phrase that was still half in English. */
  s = lookup(s);

  /* The shape of the name is read first, and the two halves are read
     again on their own, so that "gravity on a planet" becomes "行星上的
     重力" and not "重力 在 一个 行星". */
  for (const [re, make] of SHAPES) {
    const m = s.match(re);
    if (!m) continue;
    if (depth > 4) break;
    const a = translateOnce(m[1], depth + 1);
    const b = translateOnce(m[2], depth + 1);
    if (!a || !b) continue;
    return make(a, b) + kind;
  }

  return applyWords(s) + kind;
}

export function translateTitle(title) {
  const out = tidy(translateOnce(title, 0));
  return out || String(title || '').trim();
}

export default translateTitle;
