/*
 * Chinese names for the programs of The Physics Aviary.
 *
 * The names on the site are written in English; the library is read in
 * Chinese, so every name is carried over into Chinese here.  The English
 * name is kept beside it in the catalogue, so nothing is ever lost.
 *
 * The English name is taken apart in three steps.  First the phrases that
 * have to be read as a whole are found, then the shape of the name — the
 * part that says "of" or "from" or "on" — is read, and last of all the
 * single words are looked up.  The shape is read first because Chinese
 * puts the word behind, and the order of the words matters more than any
 * single word.
 */

