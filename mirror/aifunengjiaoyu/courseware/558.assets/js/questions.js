  function makeBank(id, chapter, prefix, facts, variants) {
    const questions = [];
    facts.forEach((fact, factIndex) => {
      for (let variant = 0; variant < variants; variant++) {
        const difficulty = Math.min(4, variant + 1);
        const item = q(
          `${prefix}-${String(factIndex + 1).padStart(2, "0")}-${variant + 1}`,
          variantStems[variant](fact.topic),
          fact.options,
          0,
          difficulty,
          fact.category,
          fact.explanation,
          [25, 50, 75, 100][difficulty - 1],
          `${prefix}-${String(factIndex + 1).padStart(2, "0")}`
        );
        item.sourceType = fact.sourceType || "本回合原著题";
        questions.push(item);
      }
    });
    return { id, chapter, questions };
  }

